#!/usr/bin/env python3
"""
F1DB staging schema (step 2 of docs/PLAN-2026-10-26-f1db-migration.md).

  # 1. Write the migration that creates schema f1db with F1DB's tables, indexes and views
  #    (run once per pinned release; the output is committed under supabase/migrations/):
  python3 scripts/f1db/staging.py ddl --dump f1db-sql-postgresql.sql --out supabase/migrations/<ts>_f1db_staging_schema.sql

  # 2. Apply it with the CLI (never the dashboard): supabase db push

  # 3. Load the release's rows into f1db.* (production tables are never touched):
  python3 scripts/f1db/staging.py load --dump f1db-sql-postgresql.sql [--dry-run]

The dump is F1DB's PostgreSQL release asset (f1db-sql-postgresql.zip). Every statement it runs is
rewritten to name schema f1db explicitly, and its DROP statements are discarded, so nothing
outside f1db can be created, changed or dropped. `load` empties the f1db tables first, so it can
be re-run, sends the inserts in chunks through the Supabase Management API (needs SUPABASE_ACCESS_TOKEN;
--db-url rehearses on any other Postgres through `supabase db query`), and then checks every table's row count against the dump.
"""

import argparse
import json
import os
import re
import subprocess
import sys
import tempfile
import urllib.error
import urllib.request
from collections import Counter, OrderedDict
from pathlib import Path

PROJECT_REF = "ozcmecoaofolbrzhlhum"
CHUNK_BYTES = 2_000_000
SCHEMA = "f1db"

CREATE_TABLE = re.compile(r'^CREATE TABLE "([^"]+)"', re.M)
CREATE_VIEW = re.compile(r'^CREATE VIEW "([^"]+)"', re.M)
CREATE_INDEX = re.compile(r'^(CREATE (?:UNIQUE )?INDEX "[^"]+" ON )"([^"]+)"', re.M)
REFERENCES = re.compile(r'REFERENCES "([^"]+)"')
INSERT_ROW = re.compile(r'^INSERT INTO "([^"]+)" (\([^)]*\)) VALUES (\(.*\));$')


def read_dump(path: Path) -> tuple[str, list[str]]:
    text = path.read_text(encoding="utf-8")
    first_insert = re.search(r'^INSERT INTO ', text, re.M)
    if not first_insert:
        sys.exit("no INSERT statements in the dump")
    ddl = text[: first_insert.start()]
    inserts = [line for line in text[first_insert.start():].splitlines() if line.startswith("INSERT INTO ")]
    stray = [line for line in text[first_insert.start():].splitlines() if line.strip() and not line.startswith("INSERT INTO ")]
    if stray:
        sys.exit(f"unexpected non-INSERT statements after the DDL: {stray[:3]}")
    return ddl, inserts


def qualify_ddl(ddl: str) -> str:
    # Keep CREATE statements only: the dump's DROP ... IF EXISTS lines are unqualified and are
    # not needed in a fresh schema.
    statements = [s.strip() for s in ddl.split(";") if s.strip()]
    kept = [s for s in statements if s.startswith("CREATE ")]
    out = []
    for s in kept:
        s = CREATE_TABLE.sub(lambda m: f'CREATE TABLE {SCHEMA}."{m.group(1)}"', s)
        s = CREATE_VIEW.sub(lambda m: f'CREATE VIEW {SCHEMA}."{m.group(1)}"', s)
        s = CREATE_INDEX.sub(lambda m: f'{m.group(1)}{SCHEMA}."{m.group(2)}"', s)
        s = REFERENCES.sub(lambda m: f'REFERENCES {SCHEMA}."{m.group(1)}"', s)
        out.append(s + ";")
    return "\n\n".join(out)


def cmd_ddl(args) -> None:
    ddl, _ = read_dump(args.dump)
    body = qualify_ddl(ddl)
    tables = CREATE_TABLE.findall(ddl)
    header = f"""-- F1DB staging schema (docs/PLAN-2026-10-26-f1db-migration.md, step 2).
-- Generated by scripts/f1db/staging.py from F1DB's PostgreSQL release dump ({args.release}).
-- A separate schema: no production table is created, changed or read here. Not exposed to the
-- API roles; the diff in step 3 reads it with the CLI.

create schema if not exists {SCHEMA};
revoke all on schema {SCHEMA} from public, anon, authenticated;

-- View bodies in the dump name their tables without a schema.
set search_path to {SCHEMA}, public;

"""
    footer = f"""

reset search_path;

revoke all on all tables in schema {SCHEMA} from public, anon, authenticated;
grant usage on schema {SCHEMA} to service_role;
grant select on all tables in schema {SCHEMA} to service_role;
"""
    args.out.write_text(header + body + footer, encoding="utf-8")
    print(f"wrote {args.out} ({len(tables)} tables, {len(CREATE_VIEW.findall(ddl))} views)")


def run_sql(sql: str, target: list[str] | None) -> str:
    # target None: the Supabase Management API (POST /v1/projects/{ref}/database/query), which
    # needs only SUPABASE_ACCESS_TOKEN over HTTPS. `supabase db query --linked` opens a direct
    # Postgres connection (port 5432) instead, which cloud sessions can't reach.
    if target is None:
        req = urllib.request.Request(
            f"https://api.supabase.com/v1/projects/{PROJECT_REF}/database/query",
            data=json.dumps({"query": sql}).encode(),
            headers={"Authorization": f"Bearer {os.environ['SUPABASE_ACCESS_TOKEN']}", "Content-Type": "application/json"},
            method="POST",
        )
        try:
            with urllib.request.urlopen(req, timeout=600) as resp:
                return json.dumps({"rows": json.loads(resp.read() or b"[]")})
        except urllib.error.HTTPError as exc:
            sys.exit(f"Management API query failed: HTTP {exc.code}\n{exc.read()[:2000].decode(errors='replace')}")
    with tempfile.NamedTemporaryFile("w", suffix=".sql", delete=False, encoding="utf-8") as fh:
        fh.write(sql)
        path = fh.name
    try:
        res = subprocess.run(
            ["npx", "supabase", "db", "query", *target, "--output-format", "json", "-f", path],
            capture_output=True, text=True, timeout=600,
        )
    finally:
        os.unlink(path)
    if res.returncode != 0:
        sys.exit(f"supabase db query failed:\n{res.stderr[-1000:]}\n{res.stdout[-2000:]}")
    return res.stdout


def cmd_load(args) -> None:
    ddl, inserts = read_dump(args.dump)
    tables = CREATE_TABLE.findall(ddl)
    # One statement per chunk: a multi-row INSERT into one table. `supabase db query` runs a
    # file as a single statement over --db-url, and one statement is atomic on its own.
    expected: Counter = Counter()
    chunks: list[str] = []
    cur_key, cur_vals, size = None, [], 0
    total = 0

    def flush():
        nonlocal cur_vals, size
        if cur_vals:
            table, cols = cur_key
            chunks.append(f'INSERT INTO {SCHEMA}."{table}" {cols} VALUES\n' + ",\n".join(cur_vals) + ";")
        cur_vals, size = [], 0

    for line in inserts:
        m = INSERT_ROW.match(line)
        if not m or m.group(1) not in tables:
            sys.exit(f"unexpected INSERT: {line[:120]}")
        key = (m.group(1), m.group(2))
        if key != cur_key or size + len(m.group(3)) > CHUNK_BYTES:
            flush()
            cur_key = key
        cur_vals.append(m.group(3))
        size += len(m.group(3)) + 2
        expected[m.group(1)] += 1
        total += 1
    flush()
    print(f"{total} rows into {len(tables)} tables, {len(chunks)} chunks")
    if args.dry_run:
        return

    target = ["--db-url", args.db_url] if args.db_url else None
    truncate = "TRUNCATE " + ", ".join(f'{SCHEMA}."{t}"' for t in tables) + ";"
    run_sql(truncate, target)
    for i, chunk in enumerate(chunks, 1):
        run_sql(chunk, target)
        print(f"  chunk {i}/{len(chunks)}", flush=True)

    counts_sql = " UNION ALL ".join(f"SELECT '{t}' AS t, count(*) AS n FROM {SCHEMA}.\"{t}\"" for t in tables)
    out = run_sql(counts_sql + ";", target)
    try:
        parsed = json.loads(out)
        rows_back = parsed["rows"] if isinstance(parsed, dict) else parsed
        got = {r["t"]: int(r["n"]) for r in rows_back}
    except (ValueError, KeyError, TypeError):
        got = {}
    if not got:
        print(out[:2000])
        sys.exit("could not read the row counts back")
    bad = {t: (expected[t], got.get(t)) for t in tables if expected[t] != got.get(t)}
    print(json.dumps(OrderedDict(sorted(got.items())), indent=1))
    if bad:
        sys.exit(f"row counts differ from the dump: {bad}")
    print(f"ok: all {len(tables)} tables match the dump ({sum(got.values())} rows)")


def main() -> None:
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    d = sub.add_parser("ddl")
    d.add_argument("--dump", required=True, type=Path)
    d.add_argument("--out", required=True, type=Path)
    d.add_argument("--release", required=True)
    l = sub.add_parser("load")
    l.add_argument("--dump", required=True, type=Path)
    l.add_argument("--dry-run", action="store_true")
    l.add_argument("--db-url", help="a Postgres URL instead of the linked project (to rehearse on a local database)")
    args = ap.parse_args()
    {"ddl": cmd_ddl, "load": cmd_load}[args.cmd](args)


if __name__ == "__main__":
    main()
